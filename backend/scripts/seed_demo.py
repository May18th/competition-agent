def backup_db(db_path):
    ts = time.strftime("%Y%m%d_%H%M%S")
    dst = os.path.join("C:/tmp", f"competition_backup_{ts}.db")
    os.makedirs("C:/tmp", exist_ok=True)
    src = sqlite3.connect(db_path)
    out = sqlite3.connect(dst)
    src.backup(out)
    out.close()
    src.close()
    print(f"[seed] 已备份 DB -> {dst}")


def clean_old_demo(db_path):
    conn = sqlite3.connect(db_path)
    c = conn.cursor()
    c.execute("DELETE FROM history WHERE result_data LIKE ?", (f'%"{DEMO_MARK}"%',))
    n = c.rowcount
    conn.commit()
    conn.close()
    if n:
        print(f"[seed] 已清理旧演示记录 {n} 条")


