# --------------------------------------------------------------------------
# 图表渲染：与 rich_pipeline.build_rich_assets 同一套做法（render + 唯一后缀）
# --------------------------------------------------------------------------
def render_chart_set(specs, theme):
    """specs: [{id,type,title,caption,source,data}] -> rich_charts 列表（PNG 已落盘）"""
    from chart_renderer import render
    out = []
    suffix = "%d_%s" % (int(time.time()), uuid.uuid4().hex[:6])
    for c in specs:
        path = render(dict(c), "generated", theme=theme)
        if not path:
            print(f"[seed] 图表 {c['id']} 渲染失败，跳过")
            continue
        base, ext = os.path.splitext(os.path.basename(path))
        safe = f"{base}_{suffix}{ext}"
        try:
            os.replace(path, os.path.join("generated", safe))
        except Exception:
            safe = os.path.basename(path)
        out.append({"id": c["id"], "title": c["title"], "caption": c["caption"],
                    "source": c["source"], "url": f"/generated/{safe}", "spec": c})
        print(f"[seed] 图表 {c['id']} -> {safe}")
    return out


